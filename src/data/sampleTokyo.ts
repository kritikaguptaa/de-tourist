function makeHours(
  open: string,
  close: string,
  closedDays: number[] = []
): Record<number, DayHours> {
  const map: Record<number, DayHours> = {};
  for (let d = 0; d <= 6; d++) {
    map[d] = {
      open,
      close,
      closed: closedDays.includes(d),
    };
  }
  return map;
}

